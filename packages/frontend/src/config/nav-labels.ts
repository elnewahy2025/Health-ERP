export function resolveNavLabelKey(pathname: string): string | undefined {
  if (navPathLabels[pathname]) return navPathLabels[pathname];
  const segments = pathname.split('/').filter(Boolean);
  if (segments.length > 1) return navPathLabels[`/${segments[0]}`];
  return undefined;
}
